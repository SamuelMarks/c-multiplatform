/**
 * @brief Tests basic font loading error paths and valid loading from file.
 * @return UI_ERROR_NONE on success, or an error code.
 */
static ui_error_t test_font_file_loading_paths(void) {
  FILE *f;
  const char *temp_file = "test_font_temp.ttf";
  struct ui_font_manager *manager = NULL;
  struct ui_font *font = NULL;
  struct ui_font *found_font = NULL;
  struct ui_glyph_metrics metrics;
  float ascent = 0.0f;
  float descent = 0.0f;
  float line_gap = 0.0f;
  ui_error_t rc;

  /* Write temp font file */
#if defined(_MSC_VER)
  {
    errno_t err = fopen_s(&f, temp_file, "wb");
    if (err != 0 || !f) {
      return UI_ERROR_IO_FAILED;
    }
  }
#else
  f = fopen(temp_file, "wb");
  if (!f) {
    return UI_ERROR_IO_FAILED;
  }
#endif
  fwrite(test_ttf_bytes, 1, sizeof(test_ttf_bytes), f);
  fclose(f);

  rc = ui_font_manager_create(&manager);
  if (rc != UI_ERROR_NONE) {
    remove(temp_file);
    return rc;
  }

  /* 1. Argument validation */
  rc = ui_font_manager_load_font_file(NULL, temp_file, &font);
  if (rc != UI_ERROR_INVALID_ARGUMENT) {
    ui_font_manager_destroy(manager);
    remove(temp_file);
    return 1;
  }
  rc = ui_font_manager_load_font_file(manager, NULL, &font);
  if (rc != UI_ERROR_INVALID_ARGUMENT) {
    ui_font_manager_destroy(manager);
    remove(temp_file);
    return 2;
  }
  rc = ui_font_manager_load_font_file(manager, temp_file, NULL);
  if (rc != UI_ERROR_INVALID_ARGUMENT) {
    ui_font_manager_destroy(manager);
    remove(temp_file);
    return 3;
  }

  /* 2. Non-existent file */
  rc = ui_font_manager_load_font_file(manager, "nonexistent_file_xyz.ttf",
                                      &font);
  if (rc != UI_ERROR_NOT_FOUND) {
    ui_font_manager_destroy(manager);
    remove(temp_file);
    return 4;
  }

  /* 3. Valid font file loading */
  rc = ui_font_manager_load_font_file(manager, temp_file, &font);
  if (rc != UI_ERROR_NONE || !font) {
    ui_font_manager_destroy(manager);
    remove(temp_file);
    return 5;
  }

  /* 4. Query glyph metrics and vertical metrics */
  rc = ui_font_get_glyph_metrics(font, 'A', 16.0f, &metrics);
  if (rc != UI_ERROR_NONE) {
    ui_font_manager_destroy(manager);
    remove(temp_file);
    return 6;
  }

  rc = ui_font_get_vmetrics(font, 16.0f, &ascent, &descent, &line_gap);
  if (rc != UI_ERROR_NONE) {
    ui_font_manager_destroy(manager);
    remove(temp_file);
    return 7;
  }

  /* 5. Set metadata and find via fallback chain */
  rc = ui_font_set_metadata(font, "TinyFont", 400, 0);
  if (rc != UI_ERROR_NONE) {
    ui_font_manager_destroy(manager);
    remove(temp_file);
    return 8;
  }

  rc = ui_font_manager_find_font(
      manager, "Nonexistent, 'AnotherNonexistent', TinyFont, sans-serif", 400,
      0, &found_font);
  if (rc != UI_ERROR_NONE || found_font != font) {
    ui_font_manager_destroy(manager);
    remove(temp_file);
    return 9;
  }

  rc = ui_font_manager_destroy(manager);
  remove(temp_file);
  if (rc != UI_ERROR_NONE) {
    return rc;
  }

  return UI_ERROR_NONE;
}

int main(void) {
  ui_error_t rc;

  rc = test_font_file_loading_paths();
  if (rc != UI_ERROR_NONE) {
    return (int)rc;
  }

  puts("test_ui_font_loading passed.");
  return 0;
}
